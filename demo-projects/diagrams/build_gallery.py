"""Build a local visual gallery; requires the dev extra, Doxygen and Graphviz.

Run with `uv run --locked --extra dev python demo-projects/diagrams/build_gallery.py`.
This never publishes. It writes to a fresh temporary directory unless --output
specifies a new directory. No Pillow dependency is needed to consume the fixtures.
"""

import argparse
import html
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from xml.etree import ElementTree

import yaml

REPO = Path(__file__).resolve().parents[2]
FIXTURE = REPO / "tests/integration/fixtures/image_assets"
NATIVE = Path(__file__).parent


def source_block(title: str, source: str) -> str:
    return (
        f"<details><summary>{html.escape(title)}</summary>" f"<pre><code>{html.escape(source)}</code></pre></details>"
    )


def card(title: str, description: str, image: str, source: str, links: str = "") -> str:
    return (
        '<section class="gallery-card">'
        f"<h3>{html.escape(title)}</h3><p>{html.escape(description)}</p>"
        f'<img src="{html.escape(image, quote=True)}" alt="{html.escape(title, quote=True)}">'
        f"{links}{source_block('Source', source)}</section>"
    )


def run(command: list[str], cwd: Path, env: dict[str, str], log: Path, input_text: str | None = None) -> None:
    result = subprocess.run(command, cwd=cwd, env=env, input=input_text, capture_output=True, text=True, timeout=120)
    output = result.stdout + result.stderr
    log.write_text(output, encoding="utf-8")
    if result.returncode or "error:" in output.lower() or "warning:" in output.lower():
        raise RuntimeError(f"Build reported a failure; see {log}:\n{output}")


def build(output: Path) -> Path:
    if not shutil.which("doxygen") or not shutil.which("dot"):
        raise RuntimeError("This optional gallery requires Doxygen and Graphviz dot on PATH")
    project = output / "project"
    shutil.copytree(FIXTURE, project)
    home = output / "home"
    home.mkdir()
    env = {
        "PATH": str(Path(sys.executable).parent) + os.pathsep + os.environ.get("PATH", os.defpath),
        "HOME": str(home),
        "PYTHONPATH": str(REPO),
        "PYTHONUTF8": "1",
    }
    docs = project / "docs"
    source_dir = docs / "source"
    source_dir.mkdir()
    for directory in (NATIVE, FIXTURE):
        for source in directory.iterdir():
            if source.is_file() and source.name not in {".gitignore", "README.md"}:
                shutil.copy2(source, source_dir / source.name)
    shutil.copy2(FIXTURE / "src/image_example.h", source_dir / "image_example.h")
    shutil.copy2(FIXTURE / "mkdocs.yml", source_dir / "fixture-mkdocs.yml")
    shutil.copy2(FIXTURE / "images/pipeline.svg", source_dir / "pipeline.svg")

    native_roots = {}
    for format_name in ("svg", "png"):
        work = output / f"native-{format_name}"
        shutil.copytree(NATIVE, work, ignore=shutil.ignore_patterns("output", "__pycache__"))
        doxyfile = (work / "Doxyfile").read_text(encoding="utf-8")
        doxyfile = doxyfile.replace("DOT_IMAGE_FORMAT = svg", f"DOT_IMAGE_FORMAT = {format_name}")
        run(["doxygen", "-"], work, env, output / f"native-{format_name}.log", doxyfile)
        generated = work / "output/html"
        native_roots[format_name] = generated
        shutil.copytree(generated, docs / f"native-{format_name}")

    formats = [
        ("SVG", "Authored vector source; resolution-independent.", "pipeline.svg"),
        ("PNG", "Lossless raster illustration generated by drawing commands.", "stages.png"),
        ("JPG", "Lossy JPEG encoding of an illustrative signal.", "signal.jpg"),
        ("JPEG", "Another filename extension for JPEG encoding.", "bars.jpeg"),
        ("GIF", "Four-frame animated progress illustration.", "progress.gif"),
        ("BMP", "Uncompressed raster pixel grid.", "pixels.bmp"),
        ("WebP", "Lossless raster heatmap illustration.", "coverage.webp"),
    ]
    format_cards = []
    for title, description, filename in formats:
        source = f"/**\n * @image html {filename}\n */\nclass ImageExample;\n\nIMAGE_PATH = images"
        format_cards.append(card(title, description, f"api/{filename}", source))
    (docs / "index.md").write_text(
        "# Images copied through MkDoxy\n\n"
        "These seven real assets pass through Doxygen XML and MkDoxy into the final site. "
        "Doxygen copies their content; it does not draw them. JPG and JPEG share one encoding.\n\n"
        "[View the actual generated API page](api/classImageExample.md) · "
        "[Source files](sources.md) · [Doxygen-generated diagrams](diagrams.md)\n\n"
        '<div class="gallery-grid">' + "\n".join(format_cards) + "</div>\n",
        encoding="utf-8",
    )

    native_source = (NATIVE / "gallery.h").read_text(encoding="utf-8")
    model_source = (NATIVE / "model.h").read_text(encoding="utf-8")
    model_source += "\n" + (NATIVE / "model.cpp").read_text(encoding="utf-8")
    examples = [
        (
            "Inheritance",
            "Derived automatically from C++ base classes.",
            "classgallery_1_1DocumentBuilder__inherit__graph.svg",
            model_source,
        ),
        (
            "Collaboration",
            "Derived from member types and inheritance.",
            "classgallery_1_1DocumentBuilder__coll__graph.svg",
            model_source,
        ),
        ("Includes", "Files included by gallery.h.", "gallery_8h__incl.svg", '#include "model.h"'),
        ("Included by", "Files that include model.h.", "model_8h__dep__incl.svg", '#include "model.h"'),
        ("Call graph", "Outgoing calls from the C++ entry point.", "namespacegallery_*_cgraph.svg", model_source),
        (
            "Caller graph",
            "Incoming calls to DocumentBuilder::build.",
            "classgallery_1_1DocumentBuilder_*_icgraph.svg",
            model_source,
        ),
        (
            "Inline dot",
            "Graphviz definition embedded in a Doxygen comment.",
            "dot_inline_dotgraph_1.svg",
            native_source.split(" * @dot\n", 1)[1].split(" * @enddot", 1)[0],
        ),
        (
            "External dotfile",
            "Graphviz definition from states.dot.",
            "dot_states.svg",
            (NATIVE / "states.dot").read_text(),
        ),
        (
            "Inline msc",
            "Sequence chart rendered by Doxygen's built-in mscgen.",
            "msc_inline_mscgraph_1.svg",
            native_source.split(" * @msc\n", 1)[1].split(" * @endmsc", 1)[0],
        ),
        (
            "External mscfile",
            "Sequence chart from exchange.msc.",
            "msc_exchange.svg",
            (NATIVE / "exchange.msc").read_text(),
        ),
    ]
    diagram_cards = []
    for title, description, pattern, source in examples:
        matches = list(native_roots["svg"].glob(pattern))
        if len(matches) != 1:
            raise RuntimeError(f"Expected one {title} diagram, found {matches}")
        filename = matches[0].name
        png = Path(filename).with_suffix(".png").name
        png_exists = (native_roots["png"] / png).is_file()
        links = f'<p><a href="../native-svg/{filename}">SVG source</a>'
        if png_exists:
            links += f' · <a href="../native-png/{png}">PNG version</a>'
        links += "</p>"
        diagram_cards.append(card(title, description, f"../native-svg/{filename}", source, links))
    (docs / "diagrams.md").write_text(
        "# Diagrams generated by Doxygen\n\n"
        "> **Native Doxygen output:** these graphs are generated from the source files below. "
        "They are not yet automatically rendered by MkDoxy. This gallery embeds the native output "
        "to demonstrate the distinction, not to claim new MkDoxy graph support.\n\n"
        "[Open native Doxygen HTML](native-svg/index.html) · [Source files](sources.md)\n\n"
        '<div class="gallery-grid">' + "\n".join(diagram_cards) + "</div>\n\n"
        "## Other optional diagram tools\n\n"
        "Doxygen also supports PlantUML and Dia. They require additional tools that were not "
        "used for this gallery; no rendered examples for them are claimed. "
        "Mermaid support depends on the Doxygen version.\n",
        encoding="utf-8",
    )
    sources = ["# Source files\n", "The diagrams are generated from these actual files, not from screenshots.\n"]
    for label, source in [
        ("Doxygen image comments", FIXTURE / "src/image_example.h"),
        ("Raster image generator (Pillow)", FIXTURE / "generate_assets.py"),
        ("Authored SVG", FIXTURE / "images/pipeline.svg"),
        ("MkDoxy fixture configuration", FIXTURE / "mkdocs.yml"),
        ("Native Doxygen configuration", NATIVE / "Doxyfile"),
        ("Explicit graph commands", NATIVE / "gallery.h"),
        ("C++ declarations", NATIVE / "model.h"),
        ("C++ implementations", NATIVE / "model.cpp"),
        ("Graphviz input", NATIVE / "states.dot"),
        ("Sequence chart input", NATIVE / "exchange.msc"),
    ]:
        sources.append(f"## {label}\n\n{source_block(source.name, source.read_text(encoding='utf-8'))}\n")
    (docs / "sources.md").write_text("\n".join(sources), encoding="utf-8")
    assets = docs / "assets"
    assets.mkdir()
    (assets / "gallery.css").write_text(
        ".md-grid{max-width:1600px}.md-sidebar--secondary{display:none}"
        ".gallery-grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(265px,1fr));gap:18px}"
        ".gallery-card{border:1px solid #ccd6e3;border-radius:10px;padding:16px;min-width:0}"
        ".gallery-card h3{margin-top:0}.gallery-card p{font-size:.75rem}"
        ".gallery-card img{display:block;width:100%;height:170px;object-fit:contain;background:#f6f8fb}"
        ".gallery-card pre{max-height:320px;overflow:auto;font-size:.65rem}"
        ".gallery-card details{margin-top:12px}.gallery-card summary{cursor:pointer;font-weight:bold}",
        encoding="utf-8",
    )
    config_path = project / "mkdocs.yml"
    config = yaml.safe_load(config_path.read_text())
    config.update(
        site_name="MkDoxy — image and diagram gallery",
        site_dir=str(output / "site"),
        theme={"name": "material", "palette": {"primary": "indigo"}},
        nav=[
            {"Image formats": "index.md"},
            {"Generated API": "api/classImageExample.md"},
            {"Doxygen graphs": "diagrams.md"},
            {"Sources": "sources.md"},
        ],
        extra_css=["assets/gallery.css"],
    )
    config["plugins"][0]["mkdoxy"]["save-api"] = "generated"
    config_path.write_text(yaml.safe_dump(config, sort_keys=False))
    run([sys.executable, "-m", "mkdocs", "build", "--clean", "--strict"], project, env, output / "mkdocs.log")
    return output / "site"


def export_docs_assets(output: Path) -> None:
    """Explicitly refresh the native illustrations used by the main documentation."""
    destination = REPO / "docs/media/diagrams"
    destination.mkdir(parents=True, exist_ok=True)
    shutil.copy2(FIXTURE / "images/pipeline.svg", destination / "pipeline.svg")
    native = output / "native-svg/output/html"
    for filename, pattern in {
        "inheritance.svg": "classgallery_1_1DocumentBuilder__inherit__graph.svg",
        "collaboration.svg": "classgallery_1_1DocumentBuilder__coll__graph.svg",
        "calls.svg": "namespacegallery_*_cgraph.svg",
        "sequence.svg": "msc_inline_mscgraph_1.svg",
        "includes.svg": "gallery_8h__incl.svg",
        "included-by.svg": "model_8h__dep__incl.svg",
        "callers.svg": "classgallery_1_1DocumentBuilder_*_icgraph.svg",
        "dot.svg": "dot_inline_dotgraph_1.svg",
        "dotfile.svg": "dot_states.svg",
        "mscfile.svg": "msc_exchange.svg",
    }.items():
        matches = list(native.glob(pattern))
        if len(matches) != 1:
            raise RuntimeError(f"Expected one illustration for {filename}, found {matches}")
        # These are static illustrations, not copies of the native HTML site.
        # Remove links to native pages that are not published with this guide.
        tree = ElementTree.parse(matches[0])
        for element in tree.iter():
            element.attrib.pop("{http://www.w3.org/1999/xlink}href", None)
            element.attrib.pop("href", None)
        ElementTree.register_namespace("", "http://www.w3.org/2000/svg")
        with (destination / filename).open("wb") as stream:
            tree.write(stream, encoding="utf-8", xml_declaration=True)
            stream.write(b"\n")
        png = output / "native-png/output/html" / matches[0].with_suffix(".png").name
        shutil.copy2(png, destination / Path(filename).with_suffix(".png"))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="New output directory; defaults to a fresh temporary directory")
    parser.add_argument(
        "--export-docs-assets", action="store_true", help="Refresh docs/media/diagrams; review resulting SVG changes"
    )
    args = parser.parse_args()
    if args.output is None:
        destination = Path(tempfile.mkdtemp(prefix="mkdoxy-image-gallery-"))
    else:
        destination = args.output.resolve()
        destination.mkdir(parents=True, exist_ok=False)
    site = build(destination)
    if args.export_docs_assets:
        export_docs_assets(destination)
    print(f"Gallery: {site}")
