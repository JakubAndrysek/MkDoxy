"""@package mkdoxy.plugin
MkDoxy → MkDocs + Doxygen = easy documentation generator with code snippets

MkDoxy is a MkDocs plugin for generating documentation from Doxygen XML files.
"""

import logging
import shutil
from pathlib import Path, PurePath
from typing import Callable
from urllib.parse import urlsplit

from mkdocs import exceptions
from mkdocs.config import Config, base, config_options
from mkdocs.plugins import BasePlugin
from mkdocs.structure import files, pages
from mkdocs.structure.files import File

from mkdoxy.cache import Cache
from mkdoxy.doxygen import Doxygen
from mkdoxy.doxyrun import DoxygenRun
from mkdoxy.generatorAuto import GeneratorAuto
from mkdoxy.generatorBase import GeneratorBase
from mkdoxy.generatorSnippets import GeneratorSnippets
from mkdoxy.xml_parser import XmlParser

log: logging.Logger = logging.getLogger("mkdocs")
pluginName: str = "MkDoxy"


class MkDoxy(BasePlugin):
    """! MkDocs plugin for generating documentation from Doxygen XML files."""

    _IMAGE_EXTENSIONS: set[str] = {".png", ".jpg", ".jpeg", ".gif", ".bmp", ".svg", ".webp"}

    # Config options for the plugin
    config_scheme = (
        ("projects", config_options.Type(dict, default={})),
        ("full-doc", config_options.Type(bool, default=True)),
        ("debug", config_options.Type(bool, default=False)),
        ("ignore-errors", config_options.Type(bool, default=False)),
        ("save-api", config_options.Type(str, default="")),
        ("enabled", config_options.Type(bool, default=True)),
        (
            "doxygen-bin-path",
            config_options.Type(str, default="doxygen", required=False),
        ),
    )

    # Config options for each project
    config_project = (
        ("src-dirs", config_options.Type(str)),
        ("full-doc", config_options.Type(bool, default=True)),
        ("debug", config_options.Type(bool, default=False)),
        # ('ignore-errors', config_options.Type(bool, default=False)),
        ("api-path", config_options.Type(str, default=".")),
        ("doxy-cfg", config_options.Type(dict, default={}, required=False)),
        ("doxy-cfg-file", config_options.Type(str, default="", required=False)),
        ("template-dir", config_options.Type(str, default="", required=False)),
        ("sorting", config_options.Type((bool, dict), default=True)),
        ("hideparams", config_options.Type(bool, default=False)),
        #TODO: hidetparams
    )

    def is_enabled(self) -> bool:
        """! Checks if the plugin is enabled
        @details
        @return: (bool) True if the plugin is enabled.
        """
        return self.config.get("enabled")

    def _copy_image_assets(
        self,
        source_xml_dir: Path,
        destination_dir: Path,
        *,
        image_names: set[str],
        check_collision: Callable[[PurePath, Path], None] | None = None,
    ) -> list[PurePath]:
        """Copy image assets generated by Doxygen into the MkDocs API output directory.

        Args:
            source_xml_dir: Path where Doxygen stores the XML output (and accompanying assets).
            destination_dir: Path inside MkDocs' temporary directory where generated markdown lives.
            image_names: Image references collected from current indexed XML compounds.
            check_collision: Validate original docs assets before writing any image.

        Returns:
            List of relative paths (to ``destination_dir``) for the copied images.
        """

        source_root = source_xml_dir.resolve()
        destination_root = destination_dir.resolve()
        planned: list[tuple[Path, PurePath]] = []
        for name in sorted(image_names):
            url = urlsplit(name)
            if url.scheme or url.netloc:
                continue  # Remote images are rendered as URLs, not copied locally.
            relative_path = Path(name)
            if relative_path.is_absolute():
                # Doxygen preserves site-root Markdown image URLs in XML.
                # Leave them unchanged; never interpret them as host files.
                continue
            if relative_path.suffix.lower() not in self._IMAGE_EXTENSIONS:
                continue
            image_path = source_xml_dir / relative_path
            if not image_path.resolve().is_relative_to(source_root):
                raise exceptions.PluginError(f"Doxygen image points outside the XML directory: {image_path}")
            if not image_path.is_file():
                raise exceptions.PluginError(f"Referenced Doxygen image is missing: {image_path}")
            destination_path = destination_dir / relative_path
            if not destination_path.resolve().is_relative_to(destination_root):
                raise exceptions.PluginError(
                    f"Doxygen image destination points outside the API directory: {destination_path}"
                )
            if check_collision is not None:
                check_collision(relative_path, image_path)
            planned.append((image_path, relative_path))

        # An overlapping API path must not replace another current input. A
        # byte snapshot would fix only this build, leaving the saved XML corrupt
        # for the next cached build, so reject this ambiguous mapping up front.
        source_paths = {source.resolve() for source, _ in planned}
        for source, relative in planned:
            target = (destination_dir / relative).resolve()
            if target in source_paths and target != source.resolve():
                raise exceptions.PluginError(
                    f"API image output would overwrite another referenced XML image: {target}. "
                    "Choose an API path outside the XML image input paths."
                )

        # Discovery is based on XML references, not directory traversal: current
        # images inside an overlapping destination remain valid, stale ones do not.
        for image_path, relative_path in planned:
            destination_path = destination_dir / relative_path
            try:
                destination_path.parent.mkdir(parents=True, exist_ok=True)
                if image_path.resolve() != destination_path.resolve():
                    shutil.copy2(image_path, destination_path)
            except OSError as error:
                raise exceptions.PluginError(
                    f"Failed to copy Doxygen image {image_path} to {destination_path}: {error}"
                ) from error
        return [relative_path for _, relative_path in planned]

    def on_files(self, files: files.Files, config: base.Config) -> files.Files:
        """! Called after files have been gathered by MkDocs.
        @details

        @param files: (Files) The files gathered by MkDocs.
        @param config: (Config) The global configuration object.
        @return: (Files) The files gathered by MkDocs.
        """
        if not self.is_enabled():
            return files

        def checkConfig(config_project, proData, strict: bool):
            cfg = Config(config_project, "")
            cfg.load_dict(proData)
            errors, warnings = cfg.validate()
            for config_name, warning in warnings:
                log.warning(f"  -> Config value: '{config_name}' in project '{project_name}'. Warning: {warning}")
            for config_name, error in errors:
                log.error(f"  -> Config value: '{config_name}' in project '{project_name}'. Error: {error}")

            if len(errors) > 0:
                raise exceptions.Abort(f"Aborted with {len(errors)} Configuration Errors!")
            elif strict and len(warnings) > 0:
                raise exceptions.Abort(f"Aborted with {len(warnings)} Configuration Warnings in 'strict' mode!")

        def tempDir(siteDir: str, tempDir: str, projectName: str) -> str:
            tempDoxyDir = PurePath.joinpath(Path(siteDir), Path(tempDir), Path(projectName))
            tempDoxyDir.mkdir(parents=True, exist_ok=True)
            return str(tempDoxyDir)

        self.doxygen = {}
        self.generatorBase = {}
        self.projects_config: dict[str, dict[str, any]] = self.config["projects"]
        self.debug = self.config.get("debug", False)

        # generate automatic documentation and append files in the list of files to be processed by mkdocs
        self.defaultTemplateConfig: dict = {
            "indent_level": 0,
        }

        log.info(f"Start plugin {pluginName}")

        for project_name, project_data in self.projects_config.items():
            log.info(f"-> Start project '{project_name}'")

            # Check project config -> raise exceptions
            checkConfig(self.config_project, project_data, config["strict"])

            if self.config.get("save-api"):
                cache_path = Path(self.config["save-api"]) / project_name
            else:
                cache_path = Path(config["site_dir"]) / "assets/.doxy" / project_name
            api_path = project_data.get("api-path", project_name)
            docs_root = Path(config["docs_dir"]).resolve()
            for output_path in (cache_path, cache_path / api_path):
                resolved_output = output_path.resolve()
                if resolved_output.is_relative_to(docs_root) or docs_root.is_relative_to(resolved_output):
                    raise exceptions.PluginError(
                        f"Generated Doxygen/API output must not overlap docs_dir: {output_path}. "
                        "Choose a save-api/API path outside the documentation source tree."
                    )
            tempDirApi = tempDir("", str(cache_path.parent), cache_path.name)

            # Check src changes -> run Doxygen
            doxy_cfg_override = project_data.get("doxy-cfg", {})
            if project_data.get("hideparams", False):
                hideparams_alias = 'hideparams="@xmlonly <hideparams/> @endxmlonly"'
                if "ALIASES" in doxy_cfg_override:
                    doxy_cfg_override["ALIASES"] += f" {hideparams_alias}"
                else:
                    doxy_cfg_override["ALIASES"] = hideparams_alias

            doxygenRun = DoxygenRun(
                self.config["doxygen-bin-path"],
                project_data.get("src-dirs"),
                tempDirApi,
                doxy_cfg_override,
                project_data.get("doxy-cfg-file", ""),
            )
            if doxygenRun.checkAndRun():
                log.info("  -> generating Doxygen files")
            else:
                log.info("  -> skip generating Doxygen files (nothing changes)")

            # Parse XML to basic structure
            cache = Cache()
            parser = XmlParser(cache=cache, debug=self.debug)

            # Parse basic structure to recursive Nodes
            self.doxygen[project_name] = Doxygen(
                doxygenRun.getOutputFolder(),
                parser=parser,
                cache=cache,
                sorting_cfg=project_data.get("sorting", True)
            )

            # Print parsed files
            if self.debug:
                self.doxygen[project_name].printStructure()

            # Prepare generator for future use (GeneratorAuto, SnippetGenerator)
            self.generatorBase[project_name] = GeneratorBase(
                project_data.get("template-dir", ""),
                ignore_errors=self.config["ignore-errors"],
                debug=self.debug,
            )

            if self.config["full-doc"] and project_data.get("full-doc", True):
                generatorAuto = GeneratorAuto(
                    generatorBase=self.generatorBase[project_name],
                    tempDoxyDir=tempDirApi,
                    siteDir=config["site_dir"],
                    apiPath=project_data.get("api-path", project_name),
                    doxygen=self.doxygen[project_name],
                    useDirectoryUrls=config["use_directory_urls"],
                )

                project_config = self.defaultTemplateConfig.copy()
                project_config.update(project_data)
                generatorAuto.fullDoc(project_config)

                generatorAuto.summary(project_config)

                for file in generatorAuto.fullDocFiles:
                    files.append(file)

                api_output_dir = Path(tempDirApi) / api_path
                existing_src_paths = {mkdocs_file.src_path for mkdocs_file in files}
                api_path_prefix = PurePath(api_path)

                def check_collision(relative_path: PurePath, source: Path) -> None:
                    output = (api_path_prefix / relative_path).as_posix()
                    if output not in existing_src_paths:
                        return
                    existing_file = files.get_file_from_path(output)
                    existing_source = existing_file.abs_src_path
                    if existing_source is not None and Path(existing_source).read_bytes() == source.read_bytes():
                        return
                    raise exceptions.PluginError(
                        f"Doxygen image conflicts with an existing documentation asset: {output}. "
                        "Remove the duplicate docs asset or use a different image name/API path."
                    )

                copied_images = self._copy_image_assets(
                    doxygenRun.getOutputFolder(),
                    api_output_dir,
                    image_names=self.doxygen[project_name].image_assets,
                    check_collision=check_collision,
                )

                if copied_images:
                    log.info(f"  -> prepared {len(copied_images)} Doxygen image asset(s)")
                    for relative_path in copied_images:
                        relative_output_path = (api_path_prefix / relative_path).as_posix()
                        if relative_output_path in existing_src_paths:
                            continue
                        files.append(
                            File(
                                relative_output_path,
                                tempDirApi,
                                config["site_dir"],
                                config["use_directory_urls"],
                            )
                        )
                        existing_src_paths.add(relative_output_path)
        return files

    def on_page_markdown(
        self,
        markdown: str,
        page: pages.Page,
        config: base.Config,
        files: files.Files,
    ) -> str:
        """! Generate snippets and append them to the markdown.
        @details

        @param markdown (str): The markdown.
        @param page (Page): The MkDocs page.
        @param config (Config): The MkDocs config.
        @param files (Files): The MkDocs files.
        @return: (str) The markdown.
        """
        if not self.is_enabled():
            return markdown

        # update default template config with page meta
        page_config = self.defaultTemplateConfig.copy()
        page_config.update(page.meta)

        generatorSnippets = GeneratorSnippets(
            markdown=markdown,
            generatorBase=self.generatorBase,
            doxygen=self.doxygen,
            projects=self.projects_config,
            useDirectoryUrls=config["use_directory_urls"],
            page=page,
            config=page_config,
            debug=self.debug,
        )

        return generatorSnippets.generate()


